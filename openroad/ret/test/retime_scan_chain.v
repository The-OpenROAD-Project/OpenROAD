// A 24-stage shift register of SDFF_X1 scan flip-flops; D and SI of each
// stage read the stage before it.
module top (a, b, se, clk, y);
  input a;
  input b;
  input se;
  input clk;
  output y;
  wire n0;
  wire q1;
  wire q2;
  wire q3;
  wire q4;
  wire q5;
  wire q6;
  wire q7;
  wire q8;
  wire q9;
  wire q10;
  wire q11;
  wire q12;
  wire q13;
  wire q14;
  wire q15;
  wire q16;
  wire q17;
  wire q18;
  wire q19;
  wire q20;
  wire q21;
  wire q22;
  wire q23;
  wire q24;

  AND2_X1 g0 (.A1(a), .A2(b), .ZN(n0));
  SDFF_X1 s1 (.D(n0), .SI(n0), .SE(se), .CK(clk), .Q(q1));
  SDFF_X1 s2 (.D(q1), .SI(q1), .SE(se), .CK(clk), .Q(q2));
  SDFF_X1 s3 (.D(q2), .SI(q2), .SE(se), .CK(clk), .Q(q3));
  SDFF_X1 s4 (.D(q3), .SI(q3), .SE(se), .CK(clk), .Q(q4));
  SDFF_X1 s5 (.D(q4), .SI(q4), .SE(se), .CK(clk), .Q(q5));
  SDFF_X1 s6 (.D(q5), .SI(q5), .SE(se), .CK(clk), .Q(q6));
  SDFF_X1 s7 (.D(q6), .SI(q6), .SE(se), .CK(clk), .Q(q7));
  SDFF_X1 s8 (.D(q7), .SI(q7), .SE(se), .CK(clk), .Q(q8));
  SDFF_X1 s9 (.D(q8), .SI(q8), .SE(se), .CK(clk), .Q(q9));
  SDFF_X1 s10 (.D(q9), .SI(q9), .SE(se), .CK(clk), .Q(q10));
  SDFF_X1 s11 (.D(q10), .SI(q10), .SE(se), .CK(clk), .Q(q11));
  SDFF_X1 s12 (.D(q11), .SI(q11), .SE(se), .CK(clk), .Q(q12));
  SDFF_X1 s13 (.D(q12), .SI(q12), .SE(se), .CK(clk), .Q(q13));
  SDFF_X1 s14 (.D(q13), .SI(q13), .SE(se), .CK(clk), .Q(q14));
  SDFF_X1 s15 (.D(q14), .SI(q14), .SE(se), .CK(clk), .Q(q15));
  SDFF_X1 s16 (.D(q15), .SI(q15), .SE(se), .CK(clk), .Q(q16));
  SDFF_X1 s17 (.D(q16), .SI(q16), .SE(se), .CK(clk), .Q(q17));
  SDFF_X1 s18 (.D(q17), .SI(q17), .SE(se), .CK(clk), .Q(q18));
  SDFF_X1 s19 (.D(q18), .SI(q18), .SE(se), .CK(clk), .Q(q19));
  SDFF_X1 s20 (.D(q19), .SI(q19), .SE(se), .CK(clk), .Q(q20));
  SDFF_X1 s21 (.D(q20), .SI(q20), .SE(se), .CK(clk), .Q(q21));
  SDFF_X1 s22 (.D(q21), .SI(q21), .SE(se), .CK(clk), .Q(q22));
  SDFF_X1 s23 (.D(q22), .SI(q22), .SE(se), .CK(clk), .Q(q23));
  SDFF_X1 s24 (.D(q23), .SI(q23), .SE(se), .CK(clk), .Q(q24));
  BUF_X1 g1 (.A(q24), .Z(y));
endmodule

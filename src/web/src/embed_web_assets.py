# Embed web asset files in a .cpp, so the web server can serve them without a
# -dir argument: a path -> (content, MIME type) table, gzipped where that pays.

import argparse
import gzip
import io
import os

MIME_TYPES = {
    ".html": "text/html",
    ".js": "application/javascript",
    ".css": "text/css",
    ".json": "application/json",
    ".svg": "image/svg+xml",
}

# One escape per byte value, so the loop below is a table lookup.
_OCTAL_ESCAPES = [f"\\{b:03o}" for b in range(256)]

# Octal escapes are 4 chars each; 20 bytes keeps the emitted line at 80 columns.
_BYTES_PER_LINE = 20


def gzip_bytes(data):
    """gzip with mtime=0, so the same input and zlib give the same bytes."""
    # gzip.compress() takes no mtime before Python 3.8 (Rocky Linux 8 has 3.6).
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(data)
    return buffer.getvalue()


def write_char_array(out, ident, data):
    """Write data as `static const char <ident>_data[]`, in octal escapes.

    It may contain NULs, so the table records its length."""
    escaped = "".join(map(_OCTAL_ESCAPES.__getitem__, data))
    width = _BYTES_PER_LINE * 4
    lines = (escaped[i : i + width] for i in range(0, len(escaped), width))
    out.write(f'static const char {ident}_data[] =\n    "')
    out.write('"\n    "'.join(lines))
    out.write('";\n\n')


def c_identifier(filename):
    """Convert a filename to a valid C identifier."""
    return "k_" + filename.replace(".", "_").replace("-", "_")


def emit(out, ident, path):
    """Write the file as <ident>_data, gzipped when that makes it smaller, and
    return its EmbeddedAsset initializer."""
    with open(path, "rb") as f:
        data = f.read()
    packed = gzip_bytes(data)
    gzipped = len(packed) < len(data)
    stored = packed if gzipped else data
    write_char_array(out, ident, stored)
    mime = MIME_TYPES.get(os.path.splitext(path)[1], "application/octet-stream")
    flag = "true" if gzipped else "false"
    return f'{{{ident}_data, {len(stored)}, "{mime}", {flag}, {len(data)}}}'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", "-o", required=True)
    parser.add_argument("files", nargs="+", help="Asset files to embed")
    args = parser.parse_args()

    # Built in memory, so an unreadable input leaves no partial output.
    out = io.StringIO()
    out.write("// Auto-generated by embed_web_assets.py — do not edit.\n")
    out.write('#include "web_assets.h"\n\n')
    out.write("#include <string_view>\n\n")
    out.write("namespace web {\n\n")

    rows = []
    for path in args.files:
        filename = os.path.basename(path)
        rows.append((filename, emit(out, c_identifier(filename), path)))

    # Sizes are byte counts: a gzip stream may contain a NUL.
    out.write("static const struct {\n")
    out.write("  const char* path;\n")
    out.write("  EmbeddedAsset asset;\n")
    out.write("} kAssetTable[] = {\n")
    for filename, entry in rows:
        out.write(f'    {{"/{filename}", {entry}}},\n')
    out.write("};\n\n")

    out.write("const EmbeddedAsset* findEmbeddedAsset(std::string_view path)\n")
    out.write("{\n")
    out.write("  for (const auto& entry : kAssetTable) {\n")
    out.write("    if (path == entry.path) {\n")
    out.write("      return &entry.asset;\n")
    out.write("    }\n")
    out.write("  }\n")
    out.write("  return nullptr;\n")
    out.write("}\n\n")

    out.write("}  // namespace web\n")

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(out.getvalue())


if __name__ == "__main__":
    main()

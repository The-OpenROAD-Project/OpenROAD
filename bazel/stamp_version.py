"""Writes the release version into a linked OpenROAD binary.

The binary carries a fixed-size version slot (bazel/version/version.cc): a
marker followed by the version text. This script copies the binary and
overwrites the version text with STABLE_GIT_VERSION from Bazel's stable
workspace status.

Usage (generated by //bazel:stamped_binary.bzl):
  stamp_version.py <binary> <stable-status.txt> <output> [--codesign]
"""

import argparse
import os
import subprocess
import sys

# Layout of VersionSlot in bazel/version/version.cc.
MARKER = b"OPENROAD_VERSION_SLOT_MARKER".ljust(32, b"\0")
VERSION_SIZE = 256


def read_version(stable_status):
    with open(stable_status, encoding="utf-8") as f:
        for line in f:
            key, _, value = line.rstrip("\n").partition(" ")
            if key == "STABLE_GIT_VERSION" and value:
                return value
    return "bazel-nostamp"


def stamp(data, version):
    """Returns data with version written into its one version slot."""
    start = data.find(MARKER)
    if start < 0:
        raise ValueError("no version slot found")
    if data.find(MARKER, start + 1) >= 0:
        raise ValueError("more than one version slot found")
    encoded = version.encode("utf-8")
    if len(encoded) >= VERSION_SIZE:
        raise ValueError(f"version '{version}' is longer than {VERSION_SIZE - 1} bytes")
    begin = start + len(MARKER)
    stamped = bytearray(data)
    stamped[begin : begin + VERSION_SIZE] = encoded.ljust(VERSION_SIZE, b"\0")
    return bytes(stamped)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary")
    parser.add_argument("stable_status")
    parser.add_argument("output")
    parser.add_argument(
        "--codesign",
        action="store_true",
        help="re-sign ad hoc after patching (required on macOS)",
    )
    args = parser.parse_args()

    with open(args.binary, "rb") as f:
        data = f.read()
    try:
        stamped = stamp(data, read_version(args.stable_status))
    except ValueError as e:
        sys.exit(f"error: {args.binary}: {e}")
    with open(args.output, "wb") as f:
        f.write(stamped)
    os.chmod(args.output, 0o755)

    if args.codesign:
        # Patching invalidates the signature the linker applied, and macOS
        # refuses to run an arm64 binary whose signature does not match.
        subprocess.run(
            ["/usr/bin/codesign", "--force", "--sign", "-", args.output],
            check=True,
        )


if __name__ == "__main__":
    main()
